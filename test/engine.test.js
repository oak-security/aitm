test('full pipeline resumes prior analysis and requires trees for the three highest-ranked threats', async (t) => {
  const { engine, p, providers } = await setup(t);
  engine.update(p.id, {
    revision: p.revision,
    config: { ...p.config, trees: false, coordination: 'off', treeLimit: 1 },
  });
  const call = providers.call.bind(providers);
  let treeAttempt = 0;
  providers.call = async (input) => {
    const result = await call(input);
    if (input.phase === 'stride') {
      const template = result.data.threats[0];
      result.data.threats = [
        ['TH-4', 1],
        ['TH-2', 3],
        ['TH-3', 5],
        ['TH-1', 3],
      ].map(([id, likelihood]) => ({ ...structuredClone(template), id, likelihood }));
    }
    if (input.phase === 'trees') {
      const context = JSON.parse(input.user);
      assert.deepEqual(context.topThreatIds, ['TH-3', 'TH-1', 'TH-2']);
      assert.match(input.system, /REQUIRED for EVERY/);
      const template = result.data.trees[0];
      result.data.trees = context.topThreatIds.map((threatId) => ({
        ...structuredClone(template),
        threatId,
        nodes: template.nodes.map((n) => ({
          ...n,
          id: `${threatId}-${n.id}`,
          parentId: n.parentId ? `${threatId}-${n.parentId}` : null,
        })),
      }));
      if (++treeAttempt === 1) {
        result.data.trees.pop();
        result.data.omitted = [
          { threatId: 'TH-2', reason: 'Test omission must not be accepted in full mode.' },
        ];
      }
    }
    return result;
  };
  assert.equal((await finish(engine, p.id)).status, 'completed');
  providers.calls = [];
  const run = await finish(engine, p.id, { mode: 'full' });
  assert.equal(run.status, 'completed', run.error);
  assert.deepEqual(providers.calls, ['trees', 'trees', 'coordination', 'report']);
  const current = engine.get(p.id);
  assert.deepEqual(
    current.artifacts.trees.data.trees.map((tree) => tree.threatId),
    ['TH-3', 'TH-1', 'TH-2'],
  );
  assert.equal(current.config.treeLimit, 3);
  assert.equal(current.config.trees, true);
  assert.equal(current.config.coordination, 'auto');
  assert.equal(current.artifacts.trees.generation.attempts, 2);
  assert.equal(current.artifacts.report.status, 'draft');
  assert.equal(current.artifacts.report.review, null);
  assert.ok(run.events.some((e) => e.type === 'validation_retry'));
  assert.equal(run.events.find((e) => e.type === 'request').attempt, 1);
  assert.equal(run.events.filter((e) => e.type === 'request' && e.phase === 'trees')[1].attempt, 2);
  assert.ok(
    run.events.findIndex((e) => e.type === 'request') <
      run.events.findIndex((e) => e.type === 'progress'),
  );
  assert.ok(
    run.events.findIndex((e) => e.type === 'validating') <
      run.events.findIndex((e) => e.type === 'artifact'),
  );
  const calls = providers.calls.length;
  assert.equal((await finish(engine, p.id, { mode: 'full' })).status, 'completed');
  assert.equal(providers.calls.length, calls, 'resuming a completed full run reuses artifacts');
  assert.throws(() => engine.run(p.id, { mode: 'full', phase: 'trees' }), /single phase/);
});

